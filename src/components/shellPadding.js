/*
 * 三個外殼（PageShell／ArticleLayout／DashboardLayout）共用的水平內距。
 *
 * 為什麼要有這個檔：內距原本各殼寫死 `px-4 sm:px-6`，寬螢幕上正文就從離視窗左緣 24px 的
 * 地方開始——整片文字貼著螢幕邊，讀起來累。曾經只在譯語表那一頁傳 `padX` 補救，於是
 * 「補過的頁」與「沒補的頁」永遠會有兩種樣子，而每開一頁新的都會再犯一次。
 * 現在把留白做成預設值，貼邊變成要明講的例外（`SHELL_PAD_X_TIGHT`）。
 *
 * 三個值的斷點一律從 `px-4 sm:px-6` 起跳：**手機與平板不加內距**。窄螢幕上每一個
 * pixel 都要拿來放字，左右各留 16px 已經夠把文字與螢幕邊緣分開；把桌機的留白照搬到
 * 手機，只會把行長壓到一行放不了幾個字，換行變多、讀得更累。留白只從 `lg`（1024px）
 * 開始長，`xl`（1280px）再長一階。
 */

/* 預設：單一內容欄的殼。lg 以上左右各留 4rem、xl 以上 6rem。 */
export const SHELL_PAD_X = 'px-4 sm:px-6 lg:px-16 xl:px-24';

/*
 * 已經有側欄擋在內容與螢幕邊之間的殼（三欄的 ArticleLayout、寬版 PageShell）。
 * 側欄本身就是一段留白，再加滿版內距會把中間的閱讀欄擠窄，所以留一半。
 */
export const SHELL_PAD_X_RAIL = 'px-4 sm:px-6 lg:px-10 xl:px-16';

/*
 * 例外：整欄是寬表格、或橫向就是不夠用的頁面。傳這個要有理由——它換回的是
 * 「正文貼著螢幕邊」那個樣子。
 */
export const SHELL_PAD_X_TIGHT = 'px-4 sm:px-6';
